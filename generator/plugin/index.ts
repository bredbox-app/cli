/**
 * @fileoverview The Forge plugin that generates `src/generated/`.
 *
 * Forge parses the annotated OpenAPI document and calls `generate` once
 * with the whole model, then `generateGroup` for each group. One file is
 * written per top-level group, holding its commands and subgroups as data
 * of the types in `src/types.ts`, plus an `index.ts` that lists them.
 *
 * `scripts/generate.ts` compiles this module to WebAssembly with
 * `forge-plugin build` and runs it with `forge --target wasm://...`.
 * @author Nicholas C. Zakas
 */

//-----------------------------------------------------------------------------
// Imports
//-----------------------------------------------------------------------------

import {
	definePlugin,
	type File,
	type Forge,
	type Group,
} from "@cloudflare/forge/plugin";
import { commandGroup } from "./command.ts";

//-----------------------------------------------------------------------------
// Helpers
//-----------------------------------------------------------------------------

/**
 * The header of every generated file.
 * @param what What the file holds.
 * @returns The header comment.
 */
function header(what: string): string {
	return [
		"/**",
		` * @fileoverview ${what}`,
		" *",
		" * Generated by Cloudflare Forge from the Bredbox OpenAPI document.",
		" * Do not edit by hand: run `npm run generate` instead.",
		" */",
		"",
	].join("\n");
}

/**
 * Serializes data as a TypeScript expression.
 * @param value The data.
 * @returns The expression.
 */
function literal(value: unknown): string {
	return JSON.stringify(value, null, "\t");
}

/**
 * Returns the top-level groups of the forge, sorted by name.
 * @param forge The forge.
 * @returns The groups.
 */
function topLevel(forge: Forge): Group[] {
	return forge.groups.filter(group => group.parent === undefined);
}

/**
 * Writes the file of a top-level group.
 * @param group The group.
 * @returns The file.
 */
function groupFile(group: Group): File {
	const data = commandGroup(group);
	const content = [
		header(`Commands for \`bredbox ${data.name}\`.`),
		'import type { CommandGroup } from "../types.js";',
		"",
		`export const ${group.name.camel()}: CommandGroup = ${literal(data)};`,
		"",
	].join("\n");

	return { path: `${data.name}.ts`, content };
}

/**
 * Writes the index that lists every top-level group.
 * @param forge The forge.
 * @returns The file.
 */
function indexFile(forge: Forge): File {
	const groups = topLevel(forge);
	const imports = groups.map(
		group =>
			`import { ${group.name.camel()} } from "./${group.name.kebab()}.js";`,
	);
	const [title = "Bredbox API"] = forge.description.split("\n");
	const info = {
		title,
		version: forge.version,
		baseUrl: forge.baseUrl,
	};
	const content = [
		header("The commands generated from the API, by group."),
		'import type { ApiInfo, CommandGroup } from "../types.js";',
		...imports,
		"",
		`export const api: ApiInfo = ${literal(info)};`,
		"",
		"export const groups: CommandGroup[] = [",
		...groups.map(group => `\t${group.name.camel()},`),
		"];",
		"",
	].join("\n");

	return { path: "index.ts", content };
}

//-----------------------------------------------------------------------------
// Exports
//-----------------------------------------------------------------------------

export const { generate, generateGroup } = definePlugin({
	generate(forge) {
		return [indexFile(forge)];
	},

	generateGroup(group) {
		// Subgroups are written inside the file of their top-level group.
		return group.parent === undefined ? [groupFile(group)] : [];
	},
});
